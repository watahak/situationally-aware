"""Opinion tab — renders the No-BS executive brief with embedded Signal charts.

The opinion markdown (analysis/YYYY-MM-opinion.md) is generated by the
/generate-opinion skill. It may contain chart embed directives that this
module parses and replaces with live interactive charts from the Signal tab.

Supported embed directives (one per line in the markdown):
    <!-- chart:ratio:SLUG -->      Ratio spread chart (e.g., spy-rsp, vxus-spy)
    <!-- chart:zscore:SLUG -->     Z-score bar chart for a pair
    <!-- chart:heatmap -->         Momentum ROC heatmap
    <!-- chart:financialization --> GDP vs market-cap gap bars
    <!-- chart:gauges -->          CTA / dealer gamma / vol-target gauges
    <!-- chart:sankey -->          AI capex circular revenue flow
    <!-- chart:butterfly -->       Physical economy vs financial weight
"""

from __future__ import annotations

import re
from pathlib import Path

import pandas as pd
import streamlit as st

from core import (
    calc_financialization_gap,
    calc_ratio,
    calc_roc_table,
    calc_sma,
    calc_zscore,
    pair_display_name,
)
from settings.market import CONFIG, MACRO_ANCHORS

ANALYSIS_DIR = Path(__file__).resolve().parent.parent / "analysis"

_EMBED_RE = re.compile(r"<!--\s*chart:(\S+?)(?::(\S+?))?\s*-->")


def _get_latest(report_type: str) -> str | None:
    if not ANALYSIS_DIR.exists():
        return None
    matches = sorted(ANALYSIS_DIR.glob(f"*-{report_type}.md"), reverse=True)
    if not matches:
        return None
    return matches[0].read_text()


def _slug_to_pair(slug: str) -> dict | None:
    for pair in CONFIG["ratio_pairs"]:
        pair_slug = pair["name"].lower().replace(" / ", "-").replace("/", "-")
        if pair_slug == slug:
            return pair
    return None


def _render_embed(
    chart_type: str,
    slug: str | None,
    prices: pd.DataFrame,
    settings: dict,
    *,
    render_echart,
    chart_builders: dict,
    embed_idx: int,
) -> bool:
    """Render one embed directive. Returns True if a chart was rendered."""
    cutoff = pd.Timestamp.now() - pd.Timedelta(days=settings["lookback_days"])

    if chart_type == "ratio" and slug:
        pair = _slug_to_pair(slug)
        if not pair:
            return False
        num, denom = pair["numerator"], pair["denominator"]
        if num not in prices.columns or denom not in prices.columns:
            return False
        ratio = calc_ratio(prices, num, denom)
        sma_dict: dict[str, pd.Series] = {}
        for length in CONFIG["sma_lengths"]:
            if (length == 50 and settings["sma_50_enabled"]) or (
                length == 200 and settings["sma_200_enabled"]
            ):
                sma_dict[f"{length}-SMA"] = calc_sma(ratio, length)
        ratio_d = ratio.loc[ratio.index >= cutoff]
        sma_d = {k: v.loc[v.index >= cutoff] for k, v in sma_dict.items()}
        display = pair_display_name(pair)
        render_echart(
            chart_builders["build_ratio_echart"](ratio_d, sma_d, display),
            key=f"opinion-ratio-{slug}-{embed_idx}",
            height=390,
            alt=f"{display} ratio spread chart.",
        )
        return True

    if chart_type == "zscore" and slug:
        pair = _slug_to_pair(slug)
        if not pair:
            return False
        num, denom = pair["numerator"], pair["denominator"]
        if num not in prices.columns or denom not in prices.columns:
            return False
        ratio = calc_ratio(prices, num, denom)
        zscore = calc_zscore(ratio, CONFIG["zscore_window"])
        zscore_d = zscore.loc[zscore.index >= cutoff]
        display = pair_display_name(pair)
        render_echart(
            chart_builders["build_zscore_echart"](
                zscore_d, CONFIG["zscore_thresholds"], display
            ),
            key=f"opinion-zscore-{slug}-{embed_idx}",
            height=340,
            alt=f"{display} Z-score bars.",
        )
        return True

    if chart_type == "heatmap":
        roc_df = calc_roc_table(prices, CONFIG["roc_windows"])
        if roc_df.empty:
            return False
        render_echart(
            chart_builders["build_heatmap_echart"](roc_df),
            key=f"opinion-heatmap-{embed_idx}",
            height=max(300, 36 * len(roc_df)),
            alt="Momentum ROC heatmap.",
        )
        return True

    if chart_type == "financialization":
        gap_df = calc_financialization_gap(MACRO_ANCHORS["regions"])
        render_echart(
            chart_builders["build_financialization_echart"](gap_df),
            key=f"opinion-fin-{embed_idx}",
            height=max(300, 80 * len(gap_df)),
            alt="GDP vs market-cap gap chart.",
        )
        return True

    if chart_type == "gauges":
        ctx = chart_builders["load_context"]("systematic-positioning")
        if not ctx:
            return False
        render_echart(
            chart_builders["build_gauges_echart"](ctx),
            key=f"opinion-gauges-{embed_idx}",
            height=260,
            alt="Systematic positioning gauges.",
        )
        return True

    if chart_type == "sankey":
        ctx = chart_builders["load_context"]("mag7-circular-revenue")
        if not ctx:
            return False
        render_echart(
            chart_builders["build_sankey_echart"](ctx),
            key=f"opinion-sankey-{embed_idx}",
            height=420,
            alt="AI capex circular revenue flow.",
        )
        return True

    if chart_type == "butterfly":
        ctx = chart_builders["load_context"]("physical-anchors")
        if not ctx:
            return False
        render_echart(
            chart_builders["build_butterfly_echart"](
                ctx["data"], MACRO_ANCHORS["regions"]
            ),
            key=f"opinion-butterfly-{embed_idx}",
            height=400,
            alt="Physical economy vs financial weight.",
        )
        return True

    return False


def _render_opinion_with_charts(
    content: str,
    prices: pd.DataFrame,
    settings: dict,
    *,
    render_echart,
    chart_builders: dict,
) -> None:
    """Split opinion markdown on embed directives, render text and charts."""
    parts = _EMBED_RE.split(content)
    # parts alternates: text, chart_type, slug|None, text, chart_type, slug|None, ...
    embed_idx = 0
    i = 0
    while i < len(parts):
        if i % 3 == 0:
            text = parts[i].strip()
            if text:
                st.markdown(text)
        else:
            chart_type = parts[i]
            slug = parts[i + 1] if (i + 1) < len(parts) else None
            _render_embed(
                chart_type,
                slug,
                prices,
                settings,
                render_echart=render_echart,
                chart_builders=chart_builders,
                embed_idx=embed_idx,
            )
            embed_idx += 1
            i += 1  # skip the slug group
        i += 1


def render_opinion_tab(
    settings: dict,
    prices: pd.DataFrame,
    *,
    theme_mode: str = "dark",
    render_echart,
    chart_builders: dict,
    nav_html: str = "",
) -> None:
    """Render the Opinion tab.

    Parameters
    ----------
    render_echart : callable
        The ``render_echart_inview`` function from ``app.py`` (passed to
        avoid circular imports since ``app.py`` is the Streamlit entry point).
    chart_builders : dict
        Mapping of builder name -> callable, sourced from ``app.py``.
        Required keys: build_ratio_echart, build_zscore_echart,
        build_heatmap_echart, build_financialization_echart,
        build_gauges_echart, build_sankey_echart, build_butterfly_echart,
        load_context.
    nav_html : str
        Pre-built tab-arrow navigation HTML to place at the bottom.
    """
    opinion_content = _get_latest("opinion")
    if opinion_content:
        _render_opinion_with_charts(
            opinion_content,
            prices,
            settings,
            render_echart=render_echart,
            chart_builders=chart_builders,
        )
    else:
        st.info(
            "No opinion brief yet. Run `/generate-opinion` in Claude Code "
            "after running `/analyze-macro` to generate the executive brief."
        )

    if nav_html:
        st.html(nav_html, unsafe_allow_javascript=True)
